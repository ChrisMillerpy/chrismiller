// Writes cathy/worker/wrangler.local.jsonc: the real config minus the container, with the
// demo model and box switched on. Used for local runs and the local end-to-end test.
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../worker/wrangler.jsonc', import.meta.url);
const strip = (s) => s.replace(/^\s*\/\/.*$/gm, '').replace(/,(\s*[}\]])/g, '$1');
const cfg = JSON.parse(strip(readFileSync(src, 'utf8')));
delete cfg.containers;
delete cfg.exports.Sandbox.container;
delete cfg.$schema;
// Share links point at the local share Worker (npm run dev:cathy serves it on its own port; see README).
cfg.vars = { ...cfg.vars, FAKE_MODEL: '1', FAKE_BOX: '1', SHARE_URL: process.env.SHARE_URL ?? 'http://localhost:8788' };
writeFileSync(new URL('../worker/wrangler.local.jsonc', import.meta.url), '// Generated by cathy/e2e/local-config.mjs. Do not edit.\n' + JSON.stringify(cfg, null, 2) + '\n');
console.log('wrote cathy/worker/wrangler.local.jsonc');
